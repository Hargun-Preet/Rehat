"""Coverage report for WBGT (stations by month, % missing) and seed check for 31 Oct 2025."""
from __future__ import annotations

import pandas as pd

from rehat.ingest.normalise import load_seed_d1031
from rehat.paths import DOCS, PROCESSED

EXPECTED_PER_DAY = 96  # 15-minute readings


def seed_check(wbgt: pd.DataFrame, tol: float = 0.05) -> pd.DataFrame:
    seed = load_seed_d1031()
    api = wbgt[wbgt.ts_sgt.dt.date == pd.Timestamp("2025-10-31").date()][["station_id", "ts_sgt", "wbgt"]]
    m = seed.merge(api, on=["station_id", "ts_sgt"], how="left", suffixes=("_seed", "_api"))
    m["abs_diff"] = (m.wbgt_seed - m.wbgt_api).abs()
    out = m.groupby("station_id").agg(
        readings=("wbgt_seed", "size"),
        matched=("wbgt_api", "count"),
        max_abs_diff=("abs_diff", "max"),
    )
    out["within_tol"] = (out.matched == out.readings) & (out.max_abs_diff <= tol)
    return out.reset_index()


def coverage_table(wbgt: pd.DataFrame) -> pd.DataFrame:
    w = wbgt.copy()
    w["month"] = w.ts_sgt.dt.to_period("M").astype(str)
    w["day"] = w.ts_sgt.dt.date
    valid = w.dropna(subset=["wbgt"])
    got = valid.groupby(["station_id", "month"]).size().rename("readings")
    days_in_data = w.groupby("month")["day"].nunique().rename("days_pulled")
    cov = got.reset_index().merge(days_in_data.reset_index(), on="month")
    cov["pct_missing"] = (100 * (1 - cov.readings / (cov.days_pulled * EXPECTED_PER_DAY))).clip(lower=0).round(1)
    return cov


def write_report() -> str:
    wbgt = pd.read_parquet(PROCESSED / "wbgt_15min.parquet")
    cov = coverage_table(wbgt)
    pivot = cov.pivot(index="station_id", columns="month", values="pct_missing").sort_index()
    days = wbgt.ts_sgt.dt.date.nunique()
    sc = seed_check(wbgt)
    lines = [
        "# Data coverage: NEA WBGT (data.gov.sg)",
        "",
        f"Generated by `python -m rehat.ingest.coverage`. Days pulled: {days} "
        f"({wbgt.ts_sgt.min():%Y-%m-%d} to {wbgt.ts_sgt.max():%Y-%m-%d}). Stations seen: {wbgt.station_id.nunique()}.",
        "",
        "Percent of expected 15-minute readings missing, by station and month (blank = station not reporting that month).",
        "Expected = days pulled in the month x 96.",
        "",
        "| station | " + " | ".join(pivot.columns) + " |",
        "|---|" + "---|" * len(pivot.columns),
    ]
    for sid, row in pivot.iterrows():
        lines.append(f"| {sid} | " + " | ".join("" if pd.isna(v) else f"{v:.1f}" for v in row) + " |")
    lines += [
        "",
        "## Seed check: 31 Oct 2025 (data/seed/d1031.csv vs API)",
        "",
        f"Stations within 0.05 C on every reading: {int(sc.within_tol.sum())} of {len(sc)}.",
        "",
        "| station | seed readings | matched in API | max abs diff (C) | within 0.05 |",
        "|---|---|---|---|---|",
    ]
    for _, r in sc.iterrows():
        lines.append(f"| {r.station_id} | {r.readings} | {r.matched} | {r.max_abs_diff:.2f} | {'yes' if r.within_tol else 'no'} |")
    text = "\n".join(lines) + "\n"
    (DOCS / "data-coverage.md").write_text(text)
    return text


if __name__ == "__main__":
    print(write_report()[-1500:])
